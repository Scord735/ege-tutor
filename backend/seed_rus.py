def seed():
    init_db()
    db = SessionLocal()
    try:
        if db.query(Subject).filter_by(code="rus").first():
            print(">> [rus] уже в базе — пропускаю")
            return
        print(">> [rus] заливаю...")
        subject = Subject(name="Русский язык", code="rus",
                          description="ЕГЭ по русскому языку, 27 заданий, ФИПИ 2026")
        db.add(subject)
        db.flush()
        for tg_data in STRUCTURE:
            tg = TaskGroup(subject_id=subject.id, task_number=tg_data["n"],
                           name=tg_data["name"])
            db.add(tg)
            db.flush()
            for idx, t in enumerate(tg_data["topics"], start=1):
                db.add(Topic(task_group_id=tg.id, name=t, order_index=idx))
        db.commit()
        n_topics = sum(len(tg["topics"]) for tg in STRUCTURE)
        print(f">> [rus] готово: {len(STRUCTURE)} заданий, {n_topics} тем")
    finally:
        db.close()


